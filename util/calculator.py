def add_num (a,b):
    """returns sum of a and b"""
    return a + b
def divide_num (a,b):
    """returns quotient of a and b"""
    return a / b
def subtract_num (a,b):
    """returns subtraction of a and b"""
    return a - b
def power_num (a,b):
    """returns a to power of b"""

    return a ** b


